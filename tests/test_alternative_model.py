"""Unit tests for AlternativeDemoClient and demo-only generation."""

import json
from unittest.mock import MagicMock, patch
import pytest

from factindic.models.alternative import AlternativeDemoClient, load_local_factindic_env
from factindic.models.base import GenerationResult


def test_alternative_demo_client_guard(monkeypatch):
    """Verify that AlternativeDemoClient raises RuntimeError when no credentials exist."""
    monkeypatch.setattr("factindic.models.alternative.load_local_factindic_env", lambda: {})
    for var in [
        "GEMINI_API_KEY", "GOOGLE_API_KEY",
        "GROQ_API_KEY", "OPENAI_API_KEY",
        "COHERE_API_KEY", "CO_API_KEY",
        "HF_TOKEN", "HUGGINGFACE_API_KEY",
    ]:
        monkeypatch.delenv(var, raising=False)

    with pytest.raises(RuntimeError, match="No valid API credentials found"):
        AlternativeDemoClient()


def test_alternative_demo_client_init_with_key():
    """Verify initialization when key is explicitly provided."""
    client = AlternativeDemoClient(
        provider="google",
        model_id="gemini-2.5-flash",
        api_key="mock_key_for_unit_tests",
    )
    assert client.provider == "google"
    assert client.model_id == "gemini-2.5-flash"
    assert "mock_key_for_unit_tests" in client.endpoint


def test_alternative_demo_client_generate_google():
    """Verify response parsing for Google API format."""
    client = AlternativeDemoClient(
        provider="google",
        model_id="gemini-2.5-flash",
        api_key="mock_key",
    )

    mock_response_data = {
        "candidates": [
            {
                "content": {
                    "parts": [{"text": "This is a concise test summary generated by Gemini."}]
                }
            }
        ]
    }

    mock_resp = MagicMock()
    mock_resp.read.return_value = json.dumps(mock_response_data).encode("utf-8")
    mock_resp.__enter__.return_value = mock_resp

    with patch("urllib.request.urlopen", return_value=mock_resp):
        res = client.generate("Summarize this article.")
        assert isinstance(res, GenerationResult)
        assert res.text == "This is a concise test summary generated by Gemini."
        assert res.model_id == "gemini-2.5-flash"
        assert res.provider == "google"


